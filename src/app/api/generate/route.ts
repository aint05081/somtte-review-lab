import OpenAI from "openai";
import { NextResponse } from "next/server";
import { sampleReferences } from "@/lib/reviews";
import {
  GENERATION_RULES,
  PRODUCT_PROFILES,
  STYLE_PROFILE,
} from "@/lib/prompt";
import {
  buildStylePlan,
  stylePlanText,
} from "@/lib/style-plan";

type Body = {
  product?: "centella" | "solanum";
  experience?: string;
  length?: "auto" | "short" | "medium" | "long";
  count?: number;
};

export const runtime = "nodejs";

export async function POST(req: Request) {
  try {
    if (!process.env.OPENAI_API_KEY) {
      return NextResponse.json(
        {
          error:
            "OPENAI_API_KEY가 설정되지 않았습니다. .env.local을 확인해주세요.",
        },
        { status: 500 }
      );
    }

    const body = (await req.json()) as Body;

    const product =
      body.product === "solanum"
        ? "solanum"
        : "centella";

    const experience = String(
      body.experience || ""
    )
      .trim()
      .slice(0, 5000);

    const count = Math.min(
      Math.max(Number(body.count || 1), 1),
      20
    );

    const length = body.length || "auto";

    /**
     * 올리브영 실제 리뷰 문체 샘플 +
     * 해당 솜떼 제품 소구 샘플
     */
    const refs = sampleReferences(product);

    /**
     * 리뷰별
     * - 길이
     * - 스타일
     * - 정돈도
     * - 구두점
     * - 구어체 강도
     * - 이모지
     * - ㅎㅎ/ㅋㅋ/ㅠㅠ
     * 를 미리 배정
     */
    const stylePlan = buildStylePlan(
      count,
      length
    );

    const productName =
      product === "centella"
        ? "솜떼 센텔라 카밍 코튼볼 패드"
        : "솜떼 솔라눔 올클리어 코튼볼 패드";

    const lengthRule =
      length === "short"
        ? "짧은 후기 중심. 대체로 60자 이하이며 1~3문장 정도. 한두 가지 포인트만 툭 말하고 끝나도 된다."
        : length === "medium"
        ? "중간 길이 후기 중심. 대체로 61~150자. 문장 수와 줄바꿈은 리뷰마다 다르게 한다."
        : length === "long"
        ? "상세 경험형 후기 중심. 대체로 151자 이상이지만 모든 리뷰를 같은 길이로 맞추지 않는다."
        : "올리브영 실제 분포처럼 짧은 후기/중간 후기/상세 후기를 자연스럽게 섞는다.";

    /**
     * 입력창 사용 여부에 따라 완전히 다른 모드
     */
    const modeRule = experience
      ? `
[입력 기반 모드]

사용자가 직접 넣은 경험/포인트:
${experience}

이 내용이 이번 작업의 가장 중요한 사실 기준이다.

반드시 지킬 것:
- 사용자가 적은 경험과 방향을 유지한다.
- 입력에 없는 피부 타입을 새로 만들지 않는다.
- 입력에 없는 사용 기간을 새로 만들지 않는다.
- 입력에 없는 구매 계기나 재구매 경험을 새로 만들지 않는다.
- 입력에 없는 구체적인 효과나 피부 변화를 새로 만들지 않는다.
- 입력에 없는 전문가 언급, 피부과 경험, 임상 수치 등을 추가하지 않는다.
- 제품 프로필은 표현을 풍부하게 이해하기 위한 보조 자료로만 사용한다.

여러 개를 생성해도 입력 사실은 유지하되,
리뷰별 말투, 길이, 시작 방식, 문장 정돈 정도,
구어체 강도, 이모지와 문장부호 사용만 다양하게 바꾼다.
`
      : `
[자동 생성 모드]

사용자 경험 입력이 없다.

해당 제품 실제 솜떼 리뷰 데이터에서 반복 확인되는 소구와 사용 맥락만 활용해
일반적인 가상 소비자 리뷰 샘플을 만든다.

반드시 지킬 것:
- 센텔라와 솔라눔 올클리어의 소구를 섞지 않는다.
- 한 리뷰에 모든 제품 장점을 집어넣지 않는다.
- 리뷰 하나에는 보통 1~2개의 핵심 소구만 사용한다.
- 피부 타입, 구매 계기, 사용 상황, 첫 반응, 장점, 아쉬움, 재구매 등의 요소를 모든 리뷰에 다 넣지 않는다.
- 어떤 리뷰는 한 가지 사용감만 말하고 끝나도 된다.
- 어떤 리뷰는 피부 고민부터 시작할 수 있다.
- 어떤 리뷰는 생활 장면 하나만 구체적으로 말할 수 있다.
- 어떤 리뷰는 장점과 작은 아쉬움을 같이 말할 수 있다.
- 의료적 치료 효과, 전문가 보증, 객관적인 수치 개선, 임상 결과는 만들어내지 않는다.
- 제품 프로필과 실제 솜떼 리뷰에서 확인되지 않는 새로운 핵심 효능은 만들지 않는다.

자동 생성이라고 해서 모든 리뷰를
"피부 고민 → 사용 → 효과 → 만족 → 추천"
형태로 만들지 않는다.
`;

    const input = `
[작업 대상]

제품:
${productName}

요청 리뷰 수:
${count}개

길이 설정:
${lengthRule}

${modeRule}


${STYLE_PROFILE}


[이번 요청의 리뷰별 스타일 설계표 — 출력 번호와 1:1로 반드시 준수]

${stylePlanText(stylePlan)}

위 스타일 설계표는 단순 참고가 아니라
각 리뷰의 서로 다른 작성자 성향이다.

각 번호에 지정된 아래 조건을 실제 출력에 반영한다.

- 길이
- 리뷰 스타일
- 정돈도
- 구두점 스타일
- 구어체 강도
- 이모지 사용 여부
- ㅎㅎ/ㅋㅋ 허용 여부
- ㅠㅠ/ㅜㅜ 허용 여부

구체적인 적용 규칙:

1. "이모지 없음"으로 지정된 리뷰
→ 이모지를 넣지 않는다.

2. "이모지 1~2개 허용"으로 지정된 리뷰
→ 실제 결과에도 자연스러운 위치에 1~2개 정도 사용한다.
→ 단 문장마다 붙이지 않는다.

3. "정돈도 높음"
→ 비교적 맞춤법과 띄어쓰기가 정확한 일반 소비자 존댓말로 쓴다.

4. "정돈도 보통"
→ 일반 존댓말을 중심으로 하되
더라구요, 쓰는중, 그런거 같아요 같은 가벼운 흔들림이 들어갈 수 있다.

5. "정돈도 느슨함"
→ 모든 문장을 표준 맞춤법과 마침표로 정리하지 않는다.
→ 가벼운 붙여쓰기, 비표준 종결어미, 줄바꿈, 말줄임표,
ㅋㅋ/ㅎㅎ 같은 모바일 후기 흐름을 자연스럽게 허용한다.

6. "구두점 느슨/마침표 생략 가능"
→ 모든 문장을 "."으로 끝내지 않는다.
→ 느낌표, 말줄임표, 줄바꿈, ㅎㅎ, ㅋㅋ, ㅠㅠ, 이모지 등으로 자연스럽게 끝낼 수 있다.

7. "인터넷 구어체 강함"
→ 문맥에 맞는 경우
진짜, 걍, 좋음, 잘먹음, 쓰는중, 다쓰면 또 살듯,
개좋음, 굳굳, ㅋㅋ 같은 표현을 적극적으로 사용할 수 있다.
→ 단 한 리뷰에 신조어를 과도하게 몰아넣지 않는다.

8. "구어체 거의 없음"
→ 비교적 차분하고 정돈된 소비자 후기처럼 쓴다.

9. ㅎㅎ/ㅋㅋ가 허용된 리뷰
→ 허용이라고만 생각하지 말고 문맥상 어울리면 실제로 한 번 정도 사용한다.

10. ㅠㅠ/ㅜㅜ가 허용된 리뷰
→ 피부 고민, 아쉬움, 강한 만족 등의 감정이 있는 경우 실제로 자연스럽게 사용할 수 있다.

11. 스타일 설계표가 "재구매·정착템형"이어도
입력 기반 모드에서 사용자가 재구매 경험을 적지 않았다면 재구매 사실을 만들지 않는다.
→ 같은 길이와 정돈도의 다른 자연스러운 스타일로 대체한다.

12. 피부 고민 선제시형도 입력 기반 모드에서 피부 타입/고민이 없다면
없는 피부 고민을 새로 만들지 않는다.

13. 자동 생성 모드에서는 해당 제품 실제 데이터에서 확인되는 범위 안에서만
가상의 일반적 상황을 구성한다.


${PRODUCT_PROFILES[product]}


[실제 올리브영 리뷰 — 문체 관찰용]

아래 리뷰들은 내용 복사용이 아니다.

관찰해야 할 것:
- 문장 길이
- 시작 방식
- 줄바꿈
- 구어체 강도
- 맞춤법과 띄어쓰기의 정돈 정도
- ㅋㅋ/ㅎㅎ/ㅠㅠ
- 이모지
- 마침표 생략
- 말줄임표
- 느낌표
- 약간의 비정돈성
- 실제 소비자가 말을 덧붙이는 방식

독특한 문장이나 개인 에피소드를 그대로 베끼지 않는다.

${refs.olive
  .map(
    (x, i) => `${i + 1}. ${x}`
  )
  .join("\n")}


[해당 솜떼 제품 실제 리뷰 — 제품 소구/사용 맥락 확인용]

아래 리뷰는 문체를 그대로 복사하기 위한 것이 아니라
이 제품에서 실제로 어떤 사용감과 소구가 반복되는지 확인하기 위한 자료다.

${refs.productExamples
  .map(
    (x, i) => `${i + 1}. ${x}`
  )
  .join("\n")}


[최종 생성 지시]

${
  experience
    ? `
${count}개의 리뷰 샘플을 만든다.

사용자가 입력한 경험/포인트는 사실 기준으로 유지한다.

단순히 같은 문장을 ${count}번 패러프레이즈하지 않는다.

각 리뷰는 스타일 설계표에 따라
- 시작 방식
- 길이
- 문장 수
- 줄바꿈
- 정돈 정도
- 종결어미
- 감정 표현
- 이모지 여부
- ㅋㅋ/ㅎㅎ/ㅠㅠ 여부
를 실제로 다르게 한다.

어떤 리뷰는 짧게 끝나고,
어떤 리뷰는 한 가지 경험을 조금 자세히 풀고,
어떤 리뷰는 중간에 생각나는 말을 덧붙이는 흐름도 허용한다.

입력의 핵심 사실은 유지한다.
`
    : `
${count}개의 가상 소비자 리뷰 샘플을 만든다.

각 리뷰는 서로 다른 사람이 쓴 것처럼
제품 소구, 상황, 길이, 시작 방식과 말투를 분산한다.

중요:
- 한 리뷰에는 보통 핵심 제품 소구 1~2개만 사용한다.
- 모든 리뷰에서 촉촉함/부드러움/피부결/화장/재구매 등을 전부 나열하지 않는다.
- 짧은 리뷰는 설명이 부족해도 된다.
- 일부는 제품 평가부터 바로 시작한다.
- 일부는 생활 장면부터 시작한다.
- 일부는 피부 고민부터 시작한다.
- 일부는 결론부터 툭 던질 수 있다.
- 일부는 작은 아쉬움이나 망설임이 있어도 된다.
- 모든 리뷰를 추천 문장으로 끝내지 않는다.
- 모든 리뷰를 "재구매할게요"로 끝내지 않는다.
- 사용 기간을 모든 리뷰에 만들지 않는다.
- 모든 리뷰에 피부 타입을 넣지 않는다.

STYLE_PROFILE과 이번 스타일 설계표를 실제 문장에 적극 반영한다.
`
}

출력 규칙:
- 분석 과정 출력 금지
- 출처 출력 금지
- 소제목 출력 금지
- 요청된 리뷰만 번호를 붙여 출력
- 번호는 1부터 ${count}까지
`;

    const openai = new OpenAI({
      apiKey: process.env.OPENAI_API_KEY,
    });

    const response =
      await openai.responses.create({
        model:
          process.env.OPENAI_MODEL ||
          "gpt-5.4",

        instructions:
          GENERATION_RULES,

        input,

        max_output_tokens:
          count <= 3
            ? 1800
            : count <= 10
            ? 5000
            : 9000,
      });

    const text =
      response.output_text?.trim();

    if (!text) {
      throw new Error(
        "모델 응답이 비어 있습니다."
      );
    }

    return NextResponse.json({
      text,
      mode: experience
        ? "guided"
        : "auto",
    });
  } catch (e) {
    console.error(e);

    return NextResponse.json(
      {
        error:
          e instanceof Error
            ? e.message
            : "서버 오류가 발생했습니다.",
      },
      { status: 500 }
    );
  }
}